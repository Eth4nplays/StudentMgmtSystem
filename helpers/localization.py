def normalize_language(language):
    return language if language in LANGUAGES else "en"


def translate(text, language="en"):
    language = normalize_language(language)
    return TRANSLATIONS.get(language, {}).get(text, text)


def localized_month_name(month, language="en"):
    from calendar import month_name

    return translate(month_name[month], language)


def localized_asset_path(filename, language="en"):
    language = normalize_language(language)
    localized_path = Path("assets") / language / filename
    if localized_path.is_file():
        return str(localized_path)
    return str(Path("assets") / "en" / filename)
